#!/usr/bin/env python3
"""
Builds src/data/mextFoods.js from MEXT's 日本食品標準成分表（八訂）増補2023年, 第2章（データ）.

Source: 文部科学省ホームページ https://www.mext.go.jp/a_menu/syokuhinseibun/mext_00001.html
The values are rounded and edited (a subset of columns, kana readings added) — keep the credit
shown in the app's footer ("出典：文部科学省ホームページ … 編集・加工").

Usage:
  pip install openpyxl pykakasi
  python3 scripts/build-mext-foods.py path/to/20260327-mxt_kagsei-mext-000029402_02.xlsx
"""
import json
import re
import sys

import openpyxl
import pykakasi

# columns of the 「表全体」 sheet
NAME, KCAL, PROTEIN, FAT, CARBS_DIFF, CARBS_MASS, CARBS_MONO = 3, 6, 9, 12, 16, 15, 13


def num(cell):
    """MEXT cells: '(11.3)' = estimated, 'Tr' = trace, '-' = not measured, '*' = see note."""
    if cell is None:
        return None
    s = str(cell).strip().replace("(", "").replace(")", "")
    if s == "Tr":
        return 0.0
    try:
        return float(s)
    except ValueError:
        return None


def clean(name):
    return re.sub(r"\s+", " ", str(name).replace("　", " ")).strip()


def main(path):
    ws = openpyxl.load_workbook(path, read_only=True, data_only=True)["表全体"]
    kks = pykakasi.kakasi()
    rows, seen = [], set()
    for row in ws.iter_rows(values_only=True):
        if not row[1] or not re.fullmatch(r"\d{5}", str(row[1])):
            continue
        kcal = num(row[KCAL])
        if kcal is None:
            continue
        carbs = next((v for v in (num(row[CARBS_DIFF]), num(row[CARBS_MASS]), num(row[CARBS_MONO])) if v is not None), 0.0)
        name = clean(row[NAME])
        if name in seen:
            continue
        seen.add(name)
        reading = "".join(p["hira"] for p in kks.convert(name))
        reading = re.sub(r"[\s\[\]［］＜＞<>()（）・、,]", "", reading)
        r1 = lambda v: round(v or 0.0, 1)
        rows.append([name, reading, round(kcal), r1(num(row[PROTEIN])), r1(carbs), r1(num(row[FAT]))])

    out = (
        "// GENERATED by scripts/build-mext-foods.py — do not edit by hand.\n"
        "// 出典：文部科学省「日本食品標準成分表（八訂）増補2023年」"
        "（https://www.mext.go.jp/a_menu/syokuhinseibun/mext_00001.html）。\n"
        "// 一部の成分のみを抜粋し、値の丸め・読み仮名の追加などの加工を行っています。\n"
        "// Per 100 g edible portion: [name, reading, kcal, protein, carbs (available, by difference), fat]\n"
        "const ROWS = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")).replace("],[", "],\n[") + ";\n\n"
        "export const MEXT_FOODS = ROWS.map(([ja, reading, cal, protein, carbs, fat]) => ({\n"
        '  en: "", ja, reading, cal, protein, carbs, fat, region: "jp", servingGrams: 100, unit: "g"\n'
        "}));\n"
    )
    with open("src/data/mextFoods.js", "w", encoding="utf-8") as f:
        f.write(out)
    print(f"{len(rows)} foods written")


if __name__ == "__main__":
    main(sys.argv[1])
